def _resume_questions(resume_text: str) -> list[dict]:
    out = []
    for line in (resume_text or "").splitlines():
        s = line.strip().lstrip("-•*·> ").strip()
        if len(s) < 25:
            continue
        terms = sorted(set(tokenize(s)))[:3]
        out.append({
            "topic": "resume project",
            "difficulty": "medium",
            "question": f"You wrote: '{s[:160]}' — explain the design decisions, trade-offs, and what you'd change now.",
            "hints": ["Start from the problem, not the stack."],
            "tests": [], "complexity": "",
            "points": terms or ["decisions", "trade-offs"],
            "source": "candidate_resume",
            "reason": "Derived from your resume",
        })
        if len(out) >= 8:
            break
    return out


def _jd_questions(jd_text: str) -> list[dict]:
    from app.analysis.interview import generate_prep

    plan = generate_prep(jd_text)
    out = []
    for q in plan["questions"]:
        if q["source"] == "behavioral_general":
            continue
        out.append({
            "topic": q["category"], "difficulty": "medium", "question": q["question"],
            "hints": [], "tests": [], "complexity": "",
            "points": [t for t in tokenize(q["question"]) if len(t) > 4][:5],
            "source": q["source"], "reason": q["reason"],
        })
    return out


def _with_meta(items: list[dict], source: str, reason: str) -> list[dict]:
    return [{**q, "source": q.get("source", source), "reason": q.get("reason", reason)} for q in items]


def build_session_questions(mode: str, difficulty: str, jd_text: str = "",
                            resume_text: str = "", limit: int = 8) -> list[dict]:
    """Select and order questions for a session. Deterministic."""
    if mode not in MODES:
        raise ValueError(f"unknown mode '{mode}'. Choose from: {', '.join(MODES)}")
    if difficulty not in DIFFICULTIES:
        raise ValueError(f"unknown difficulty '{difficulty}'")
    max_rank = _DIFF_RANK[difficulty] + (1 if mode == "mock" else 0)

    pool: list[dict] = []
    if mode in ("resume", "mock") and resume_text.strip():
        pool += _resume_questions(resume_text)
    if mode in ("technical", "mock") and jd_text.strip():
        pool += _jd_questions(jd_text)
    if mode in ("dsa", "mock"):
        pool += _with_meta([q for q in DSA_BANK if _DIFF_RANK[q["difficulty"]] <= max_rank],
                           "dsa_bank", "Curated DSA drill")
    if mode in ("system_design", "mock"):
        pool += _with_meta([q for q in SYSTEM_DESIGN_BANK if _DIFF_RANK[q["difficulty"]] <= max_rank],
                           "system_design_bank", "Curated system-design drill")
    if mode in ("cs", "mock"):
        pool += _with_meta([q for q in CS_BANK if _DIFF_RANK[q["difficulty"]] <= max_rank],
                           "cs_bank", "Curated CS fundamentals drill")
    if mode in ("aiml", "mock"):
        jd_toks = set(tokenize(jd_text)) if jd_text.strip() else set()
        ranked = sorted(
            [q for q in AIML_BANK if _DIFF_RANK[q["difficulty"]] <= max_rank],
            key=lambda q: -(len(set(tokenize(q["topic"] + " " + q["question"])) & jd_toks)),
        ) if jd_toks else [q for q in AIML_BANK if _DIFF_RANK[q["difficulty"]] <= max_rank]
        pool += _with_meta(ranked, "aiml_bank", "Curated AI/ML drill")
    if not pool:
        raise ValueError("no questions available: provide a JD/resume or pick a drill mode")
    # Interleave so mock sessions mix categories; drills keep bank order.
    if mode == "mock":
        by_cat: dict[str, list[dict]] = {}
        for q in pool:
            by_cat.setdefault(q.get("topic", "?"), []).append(q)
        mixed: list[dict] = []
        while any(by_cat.values()):
            for cat in list(by_cat):
                if by_cat[cat]:
                    mixed.append(by_cat[cat].pop(0))
        pool = mixed
    return pool[:limit]


def evaluate_turn(question: dict, answer: str) -> dict:
    """Rule-based evaluation: expected-point coverage + missing-point feedback."""
    ans_toks = set(tokenize(answer or ""))
    hits, missed = [], []
    for point in question.get("points", []) or []:
        pt = {t for t in tokenize(point) if len(t) > 3}
        (hits if pt and len(pt & ans_toks) / len(pt) >= 0.5 else missed).append(point)
    total = len(question.get("points", []) or []) or 1
    score = round(len(hits) / total, 3)
    verdict = "strong" if score >= 0.7 else ("partial" if score >= 0.4 else "weak")
    follow_up = (
        None if verdict == "strong"
        else f"Follow-up: go deeper on {', '.join(missed[:2])} — what specifically did you miss?"
    )
    return {"score": score, "verdict": verdict, "hits": hits, "missed": missed,
            "feedback": ("Strong answer." if verdict == "strong"
                         else f"Partial coverage. Missed: {'; '.join(missed[:3])}."),
            "follow_up": follow_up}
